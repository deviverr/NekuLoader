import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { transformSync } from '../../desktop/node_modules/esbuild/lib/main.js';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const sky = readFileSync(`${root}apps/desktop/src/app/PixelSky.tsx`, 'utf8');
const cat = readFileSync(`${root}apps/desktop/src/app/PixelCat.tsx`, 'utf8');
// Reuse the app's original drawing code without adding React to the website.
const drawing = sky.slice(sky.indexOf('const PIXEL'), sky.indexOf('export function PixelSky'))
  + '\n' + cat.slice(cat.indexOf('export type CatPose'), cat.indexOf('export function PixelCat'));
const runtime = `
const skyCanvas = document.querySelector('#cosmic-sky');
const catCanvas = document.querySelector('#sleeping-neku');
const ctx = skyCanvas?.getContext('2d');
const catCtx = catCanvas?.getContext('2d');
if (ctx && catCtx) {
  const preference = matchMedia('(prefers-reduced-motion: reduce)');
  let width = 1, height = 1, stars = [], sprites = [], elapsed = 0, last = 0, raf = 0, catTick = -1;
  const palette = themeColors();
  const resize = () => {
    width = skyCanvas.width = Math.ceil(innerWidth / PIXEL);
    height = skyCanvas.height = Math.ceil(innerHeight / PIXEL);
    stars = Array.from({length: Math.min(400, Math.round(width * height / 300))}, (_, index) => ({x: Math.random() * width, y: Math.random() * height, layer: index % 3, phase: Math.random() * Math.PI * 2}));
    sprites = PLANETS.map(planet => {
      const sprite = document.createElement('canvas');
      sprite.width = sprite.height = planet.r * 4 + 4;
      const context = sprite.getContext('2d');
      if (context) drawPlanet(context, {...planet, cx: .5, cy: .5}, sprite.width, sprite.height, palette);
      return sprite;
    });
    render(0);
  };
  const drawCat = tick => {
    if (catTick === tick) return;
    catTick = tick;
    catCtx.clearRect(0, 0, W, H + 6);
    const fur = colors();
    const grid = sleepFrame(Math.floor(tick / 4));
    grid.forEach((row, y) => row.forEach((kind, x) => {
      if (kind) {catCtx.fillStyle = fur[kind]; catCtx.fillRect(x, y + 6, 1, 1);}
    }));
    for (const offset of [0, 6]) {
      const phase = (tick + offset) % 12;
      catCtx.globalAlpha = 1 - phase / 12;
      catCtx.fillStyle = fur[1];
      Z.forEach((row, dy) => row.forEach((on, dx) => {
        if (on) catCtx.fillRect(22 + Math.floor(phase / 4) + dx, 6 - Math.floor(phase / 2) + dy, 1, 1);
      }));
    }
    catCtx.globalAlpha = 1;
  };
  function render(dt) {
    ctx.clearRect(0, 0, width, height);
    sprites.forEach((sprite, index) => {
      const planet = PLANETS[index], phase = index * 1.7, orbit = elapsed * (.24 + index * .035);
      const dx = (Math.sin(orbit + phase) - Math.sin(phase)) * Math.min(12, width * .025);
      const dy = (Math.cos(orbit * .8 + phase) - Math.cos(phase)) * Math.min(9, height * .025);
      ctx.drawImage(sprite, Math.round(planet.cx * width - sprite.width / 2 + dx), Math.round(planet.cy * height - sprite.height / 2 + dy));
    });
    ctx.fillStyle = palette.star;
    for (const star of stars) {
      star.y = (star.y + dt * (3 + star.layer * 3)) % height;
      const sparkle = .65 + Math.sin(elapsed * 1.5 + star.phase) * .35;
      const x = Math.floor(star.x), y = Math.floor(star.y);
      ctx.globalAlpha = star.layer === 2 ? sparkle * .42 : .22;
      ctx.fillRect(x, y, 1, 1);
      if (star.layer === 2) {ctx.globalAlpha *= .6; ctx.fillRect(x-1,y,3,1); ctx.fillRect(x,y-1,1,3);}
    }
    ctx.globalAlpha = 1;
    drawCat(preference.matches ? 0 : Math.floor(elapsed / .28));
  }
  function loop(now) {
    if (document.hidden || preference.matches) {raf = 0; return;}
    raf = requestAnimationFrame(loop);
    if (now - last < FRAME_MS) return;
    const dt = last ? Math.min((now - last) / 1000, .1) : 0;
    last = now; elapsed += dt; render(dt);
  }
  function resume() {
    cancelAnimationFrame(raf); raf = 0; last = 0; render(0);
    if (!document.hidden && !preference.matches) raf = requestAnimationFrame(loop);
  }
  addEventListener('resize', resize);
  document.addEventListener('visibilitychange', resume);
  preference.addEventListener('change', resume);
  resize(); resume();
}
`;
const output = transformSync(drawing + '\n' + runtime, { loader: 'ts', format: 'iife', target: 'es2020', minify: true }).code;
writeFileSync(`${root}apps/site/dist/site-effects.js`, '/* Original NekuLoader pixel sky and sleeping cat; generated by scripts/build-effects.mjs. */\n' + output);
