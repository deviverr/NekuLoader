const DICTIONARIES: Record<Language, Dictionary> = {
  English: en,
  Русский: ru,
  Українська: uk,
  Español: es,
  Français: fr,
  Deutsch: de,
};

for (const language of LANGUAGES) {
  Object.assign(DICTIONARIES[language], supplemental[language]);
}

const LanguageContext = createContext<Language>("English");

export function LanguageProvider({ language, children }: { language: string; children: ReactNode }) {
  const resolved = (LANGUAGES as readonly string[]).includes(language) ? (language as Language) : "English";
  return <LanguageContext.Provider value={resolved}>{children}</LanguageContext.Provider>;
}

/** Translation lookup; falls back to English, then to the key itself. */
export function useT() {
  const language = useContext(LanguageContext);
  return useCallback(
    (key: string) => DICTIONARIES[language][key] ?? en[key] ?? key,
    [language],
  );
}

/** For code outside the provider (the App shell builds menus before it). */
export function translate(language: string, key: string): string {
  const resolved = (LANGUAGES as readonly string[]).includes(language) ? (language as Language) : "English";
  return DICTIONARIES[resolved][key] ?? en[key] ?? key;
}

export function dictionaryKeys(language: Language): string[] {
  return Object.keys(DICTIONARIES[language]);
}
